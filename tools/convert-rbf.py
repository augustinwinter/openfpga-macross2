#!/usr/bin/env python3
"""Convert a Quartus .rbf to Analogue Pocket .rbf_r by reversing the 8 bits in
each byte. This conversion was proved byte-for-byte against the CP48AN Pocket
bitstream. No bitstream data is distributed in this tool.
"""
import argparse
import hashlib
from pathlib import Path

BIT_REVERSE = bytes(int(f"{i:08b}"[::-1], 2) for i in range(256))


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("source", type=Path, help="Quartus raw .rbf")
    p.add_argument("destination", type=Path, help="New Pocket bitstream.rbf_r")
    p.add_argument("--raw-sha256", help="Expected source SHA-256 (optional)")
    p.add_argument("--output-sha256", help="Expected converted SHA-256 (optional)")
    a = p.parse_args()

    source, dest = a.source.expanduser(), a.destination.expanduser()
    if not source.is_file():
        p.error(f"source does not exist: {source}")
    if source.resolve() == dest.resolve():
        p.error("source and destination must differ")
    if dest.exists():
        p.error(f"destination already exists: {dest}")

    raw = source.read_bytes()
    input_hash = digest(raw)
    if a.raw_sha256 and input_hash.lower() != a.raw_sha256.lower():
        p.error(f"raw bitstream SHA-256 mismatch: {input_hash}")

    converted = raw.translate(BIT_REVERSE)
    output_hash = digest(converted)
    if a.output_sha256 and output_hash.lower() != a.output_sha256.lower():
        p.error(f"converted bitstream SHA-256 mismatch: {output_hash}")

    dest.parent.mkdir(parents=True, exist_ok=True)
    with dest.open("xb") as f:
        f.write(converted)
    if dest.read_bytes() != converted:
        raise RuntimeError("written output did not match generated bytes")

    print(f"RAW      {len(raw)} bytes SHA-256 {input_hash}")
    print(f"CONVERTED {len(converted)} bytes SHA-256 {output_hash}")
    print(f"OUTPUT   {dest}")


if __name__ == "__main__":
    main()
